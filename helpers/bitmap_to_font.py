import argparse
import sys
from pathlib import Path
from PIL import Image

ASCII_GLYPHS = 95

def read_png(path: Path) -> list[list[tuple[int, int, int]]]:
    with Image.open(path) as image:
        if image.format != "PNG":
            raise ValueError("input must be a PNG file")
        rgba = image.convert("RGBA")
        background = Image.new("RGBA", rgba.size, "black")
        rgb = Image.alpha_composite(background, rgba).convert("RGB")
        pixels = rgb.load()
        return [
            [pixels[x, y] for x in range(rgb.width)]
            for y in range(rgb.height)
        ]

def generate_rust(pixels: list[list[tuple[int, int, int]]]) -> str:
    height = len(pixels)
    width = len(pixels[0])
    if width % ASCII_GLYPHS:
        raise ValueError(f"bitmap width must be divisible by {ASCII_GLYPHS}")

    glyph_width = width // ASCII_GLYPHS
    bytes_per_row = (glyph_width + 7) // 8
    output = [
        f"// SPDX-License-Identifier: GPLv3\n"
        f"// Copyright (C) 2026 KeiOS Developers\n"
        f"// Generated by helpers/bitmap_to_font.py; do not edit directly.\n\n"
        f"pub const ASCII_FONT_WIDTH: usize = {glyph_width};\n"
        f"pub const ASCII_FONT_HEIGHT: usize = {height};\n\n"
        f"#[allow(unused)]\n"
        f"pub const ASCII_FONT_DEFAULT: [[[u8; {bytes_per_row}]; ASCII_FONT_HEIGHT]; "
        f"{ASCII_GLYPHS}] = ["
    ]

    for glyph in range(ASCII_GLYPHS):
        output.append(f"    // ASCII {glyph + 32} : {chr(glyph + 32)}")
        output.append("    [")
        for y in range(height):
            row_bytes = [0] * bytes_per_row
            for x in range(glyph_width):
                red, green, blue = pixels[y][glyph * glyph_width + x]
                if 299 * red + 587 * green + 114 * blue >= 128_000:
                    row_bytes[x // 8] |= 1 << (7 - x % 8)
            output.append(
                "        [" + ", ".join(f"0x{byte:02X}" for byte in row_bytes) + "],"
            )
        output.append("    ],")

    output.append("];")
    return "\n".join(output) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Generate a Rust printable-ASCII font from a horizontal PNG atlas."
    )
    parser.add_argument("png", type=Path, help="PNG containing ASCII glyphs 32–126")
    parser.add_argument(
        "-o",
        "--output",
        type=Path,
        default=(
            Path(__file__).resolve().parents[1]
            / "rust/crates/drivers/src/display/text/generated_font.rs"
        ),
        help="Rust output file (default: drivers' generated default font)",
    )
    args = parser.parse_args()

    try:
        rust = generate_rust(read_png(args.png))
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(rust, encoding="utf-8")
    except (OSError, ValueError) as error:
        print(f"error: {error}", file=sys.stderr)
        return 1

    print(f"Wrote ASCII font to {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
